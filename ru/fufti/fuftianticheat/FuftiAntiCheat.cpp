class FuftiSha256 {
private:
    uint32_t m_state[8];
    uint64_t m_count;
    uint8_t m_buffer[64];

    static inline uint32_t RotR(uint32_t x, uint32_t n) {
        return (x >> n) | (x << (32 - n));
    }
    static inline uint32_t Ch(uint32_t x, uint32_t y, uint32_t z) {
        return (x & y) ^ (~x & z);
    }
    static inline uint32_t Maj(uint32_t x, uint32_t y, uint32_t z) {
        return (x & y) ^ (x & z) ^ (y & z);
    }
    static inline uint32_t BigSigma0(uint32_t x) {
        return RotR(x, 2) ^ RotR(x, 13) ^ RotR(x, 22);
    }
    static inline uint32_t BigSigma1(uint32_t x) {
        return RotR(x, 6) ^ RotR(x, 11) ^ RotR(x, 25);
    }
    static inline uint32_t SmallSigma0(uint32_t x) {
        return RotR(x, 7) ^ RotR(x, 18) ^ (x >> 3);
    }
    static inline uint32_t SmallSigma1(uint32_t x) {
        return RotR(x, 17) ^ RotR(x, 19) ^ (x >> 10);
    }

    void Transform(const uint8_t data[64]) {
        static const uint32_t K[64] = {
            0x428a2f98, 0x71374491, 0xb5c0fbcf, 0xe9b5dba5,
            0x3956c25b, 0x59f111f1, 0x923f82a4, 0xab1c5ed5,
            0xd807aa98, 0x12835b01, 0x243185be, 0x550c7dc3,
            0x72be5d74, 0x80deb1fe, 0x9bdc06a7, 0xc19bf174,
            0xe49b69c1, 0xefbe4786, 0x0fc19dc6, 0x240ca1cc,
            0x2de92c6f, 0x4a7484aa, 0x5cb0a9dc, 0x76f988da,
            0x983e5152, 0xa831c66d, 0xb00327c8, 0xbf597fc7,
            0xc6e00bf3, 0xd5a79147, 0x06ca6351, 0x14292967,
            0x27b70a85, 0x2e1b2138, 0x4d2c6dfc, 0x53380d13,
            0x650a7354, 0x766a0abb, 0x81c2c92e, 0x92722c85,
            0xa2bfe8a1, 0xa81a664b, 0xc24b8b70, 0xc76c51a3,
            0xd192e819, 0xd6990624, 0xf40e3585, 0x106aa070,
            0x19a4c116, 0x1e376c08, 0x2748774c, 0x34b0bcb5,
            0x391c0cb3, 0x4ed8aa4a, 0x5b9cca4f, 0x682e6ff3,
            0x748f82ee, 0x78a5636f, 0x84c87814, 0x8cc70208,
            0x90befffa, 0xa4506ceb, 0xbef9a3f7, 0xc67178f2
        };

        uint32_t w[64];
        for (int i = 0; i < 16; ++i) {
            w[i] = ((uint32_t)data[i * 4] << 24) |
                   ((uint32_t)data[i * 4 + 1] << 16) |
                   ((uint32_t)data[i * 4 + 2] << 8) |
                   ((uint32_t)data[i * 4 + 3]);
        }
        for (int i = 16; i < 64; ++i) {
            w[i] = SmallSigma1(w[i - 2]) + w[i - 7] + SmallSigma0(w[i - 15]) + w[i - 16];
        }

        uint32_t a = m_state[0];
        uint32_t b = m_state[1];
        uint32_t c = m_state[2];
        uint32_t d = m_state[3];
        uint32_t e = m_state[4];
        uint32_t f = m_state[5];
        uint32_t g = m_state[6];
        uint32_t h = m_state[7];

        for (int i = 0; i < 64; ++i) {
            uint32_t t1 = h + BigSigma1(e) + Ch(e, f, g) + K[i] + w[i];
            uint32_t t2 = BigSigma0(a) + Maj(a, b, c);
            h = g;
            g = f;
            f = e;
            e = d + t1;
            d = c;
            c = b;
            b = a;
            a = t1 + t2;
        }

        m_state[0] += a;
        m_state[1] += b;
        m_state[2] += c;
        m_state[3] += d;
        m_state[4] += e;
        m_state[5] += f;
        m_state[6] += g;
        m_state[7] += h;
    }

public:
    FuftiSha256() {
        Reset();
    }

    void Reset() {
        m_state[0] = 0x6a09e667;
        m_state[1] = 0xbb67ae85;
        m_state[2] = 0x3c6ef372;
        m_state[3] = 0xa54ff53a;
        m_state[4] = 0x510e527f;
        m_state[5] = 0x9b05688c;
        m_state[6] = 0x1f83d9ab;
        m_state[7] = 0x5be0cd19;
        m_count = 0;
    }

    void Update(const uint8_t* data, size_t len) {
        size_t bufferIdx = (size_t)(m_count & 0x3F);
        m_count += len;
        size_t bufferSpace = 64 - bufferIdx;

        if (len >= bufferSpace) {
            memcpy(m_buffer + bufferIdx, data, bufferSpace);
            Transform(m_buffer);
            data += bufferSpace;
            len -= bufferSpace;
            while (len >= 64) {
                Transform(data);
                data += 64;
                len -= 64;
            }
            bufferIdx = 0;
        }
        if (len > 0) {
            memcpy(m_buffer + bufferIdx, data, len);
        }
    }

    void Final(uint8_t digest[32]) {
        uint64_t totalBits = m_count * 8;
        uint8_t pad = 0x80;
        Update(&pad, 1);
        uint8_t zero = 0x00;
        while ((m_count & 0x3F) != 56) {
            Update(&zero, 1);
        }
        uint8_t lenBytes[8];
        for (int i = 0; i < 8; ++i) {
            lenBytes[i] = (uint8_t)((totalBits >> ((7 - i) * 8)) & 0xFF);
        }
        Update(lenBytes, 8);

        for (int i = 0; i < 8; ++i) {
            digest[i * 4] = (uint8_t)((m_state[i] >> 24) & 0xFF);
            digest[i * 4 + 1] = (uint8_t)((m_state[i] >> 16) & 0xFF);
            digest[i * 4 + 2] = (uint8_t)((m_state[i] >> 8) & 0xFF);
            digest[i * 4 + 3] = (uint8_t)(m_state[i] & 0xFF);
        }
    }

    static std::string HashBytes(const void* data, size_t len) {
        FuftiSha256 ctx;
        ctx.Update((const uint8_t*)data, len);
        uint8_t dig[32];
        ctx.Final(dig);
        std::ostringstream ss;
        for (int i = 0; i < 32; ++i) {
            ss << std::hex << std::setw(2) << std::setfill('0') << (int)dig[i];
        }
        return ss.str();
    }

    static bool HashFile(const std::wstring& filePath, std::string& outHash) {
        HANDLE hFile = CreateFileW(
            filePath.c_str(),
            GENERIC_READ,
            FILE_SHARE_READ,
            NULL,
            OPEN_EXISTING,
            FILE_ATTRIBUTE_NORMAL,
            NULL
        );
        if (hFile == INVALID_HANDLE_VALUE) {
            return false;
        }
        FuftiSha256 ctx;
        const DWORD bufferSize = 65536;
        std::vector<uint8_t> buffer(bufferSize);
        DWORD bytesRead = 0;
        while (ReadFile(hFile, buffer.data(), bufferSize, &bytesRead, NULL) && bytesRead > 0) {
            ctx.Update(buffer.data(), bytesRead);
        }
        CloseHandle(hFile);

        uint8_t dig[32];
        ctx.Final(dig);
        std::ostringstream ss;
        for (int i = 0; i < 32; ++i) {
            ss << std::hex << std::setw(2) << std::setfill('0') << (int)dig[i];
        }
        outHash = ss.str();
        return true;
    }
};




