static bool InjectAntiCheatDll(HANDLE hProcess, const std::wstring& dllPath) {
    size_t pathBytes = (dllPath.length() + 1) * sizeof(wchar_t);
    void* pRemoteBuf = VirtualAllocEx(hProcess, NULL, pathBytes, MEM_COMMIT | MEM_RESERVE, PAGE_READWRITE);
    if (!pRemoteBuf) {
        return false;
    }

    SIZE_T written = 0;
    if (!WriteProcessMemory(hProcess, pRemoteBuf, dllPath.c_str(), pathBytes, &written) || written != pathBytes) {
        VirtualFreeEx(hProcess, pRemoteBuf, 0, MEM_RELEASE);
        return false;
    }

    HMODULE hK32 = GetModuleHandleA("kernel32.dll");
    LPTHREAD_START_ROUTINE pLoadLibraryW = (LPTHREAD_START_ROUTINE)GetProcAddress(hK32, "LoadLibraryW");
    if (!pLoadLibraryW) {
        VirtualFreeEx(hProcess, pRemoteBuf, 0, MEM_RELEASE);
        return false;
    }

    HANDLE hRemoteThread = CreateRemoteThread(hProcess, NULL, 0, pLoadLibraryW, pRemoteBuf, 0, NULL);
    if (!hRemoteThread) {
        VirtualFreeEx(hProcess, pRemoteBuf, 0, MEM_RELEASE);
        return false;
    }

    WaitForSingleObject(hRemoteThread, 5000);
    CloseHandle(hRemoteThread);
    VirtualFreeEx(hProcess, pRemoteBuf, 0, MEM_RELEASE);
    return true;
}

static void RunWatchdogLoop(HANDLE hProcess) {
    while (true) {
        DWORD waitRes = WaitForSingleObject(hProcess, 400);
        if (waitRes != WAIT_TIMEOUT) {
            break;
        }

        BOOL isDbgAttached = FALSE;
        if (CheckRemoteDebuggerPresent(hProcess, &isDbgAttached) && isDbgAttached) {
            TerminateProcess(hProcess, 0xC0000005);
            break;
        }

        DWORD suspectPid = 0;
        std::wstring suspectName;
        if (ScanProcessesForThreats(&suspectPid, &suspectName)) {
            TerminateSuspectProcess(suspectPid);
            TerminateProcess(hProcess, 0xC0000005);
            break;
        }

        if (ScanWindowsForThreats(&suspectPid)) {
            TerminateSuspectProcess(suspectPid);
            TerminateProcess(hProcess, 0xC0000005);
            break;
        }
    }
}

int main(int argc, char* argv[]) {
    if (argc > 1 && std::string(argv[1]) == "--demo") {
        RunDemoGameLoop();
        return 0;
    }

    PrintBanner();

    wchar_t currentExePath[MAX_PATH];
    GetModuleFileNameW(NULL, currentExePath, MAX_PATH);
    std::wstring exeDirectory = currentExePath;
    size_t lastSlash = exeDirectory.find_last_of(L"\\/");
    if (lastSlash != std::wstring::npos) {
        exeDirectory = exeDirectory.substr(0, lastSlash + 1);
    }

    std::wstring dllPath = exeDirectory + L"fuftianticheat.dll";
    std::string dllSha256;
    if (!FuftiSha256::HashFile(dllPath, dllSha256)) {
        std::cout << "FuftiAntiCheat- Check Memory - false" << std::endl;
        return 1;
    }

    std::wstring sigPath = exeDirectory + L"fuftianticheat.sig";
    std::ifstream sigFile(sigPath.c_str());
    if (sigFile.is_open()) {
        std::string expectedSha256;
        sigFile >> expectedSha256;
        sigFile.close();
        if (!expectedSha256.empty() && dllSha256 != expectedSha256) {
            std::cout << "FuftiAntiCheat- Check Memory - false" << std::endl;
            return 1;
        }
    } else {
        std::ofstream makeSig(sigPath.c_str());
        if (makeSig.is_open()) {
            makeSig << dllSha256;
            makeSig.close();
        }
    }

    std::wstring targetGamePath;
    if (argc > 1) {
        std::string argStr = argv[1];
        targetGamePath = std::wstring(argStr.begin(), argStr.end());
    } else {
        std::wstring defaultGame = exeDirectory + L"game.exe";
        HANDLE hCheck = CreateFileW(defaultGame.c_str(), GENERIC_READ, FILE_SHARE_READ, NULL, OPEN_EXISTING, 0, NULL);
        if (hCheck != INVALID_HANDLE_VALUE) {
            CloseHandle(hCheck);
            targetGamePath = defaultGame;
        } else {
            targetGamePath = currentExePath;
        }
    }

    std::string gameSha256;
    if (!FuftiSha256::HashFile(targetGamePath, gameSha256)) {
        std::cout << "FuftiAntiCheat- Check Memory - false" << std::endl;
        return 1;
    }

    DWORD foundPid = 0;
    std::wstring foundName;
    if (ScanProcessesForThreats(&foundPid, &foundName)) {
        TerminateSuspectProcess(foundPid);
        std::cout << "FuftiAntiCheat- Check Memory - false" << std::endl;
        return 2;
    }
    if (ScanWindowsForThreats(&foundPid)) {
        TerminateSuspectProcess(foundPid);
        std::cout << "FuftiAntiCheat- Check Memory - false" << std::endl;
        return 2;
    }

    if (CheckDebuggerPresentNative() || CheckHardwareBreakpointsCurrentThread() || CheckApiHooks()) {
        std::cout << "FuftiAntiCheat- Check Memory - false" << std::endl;
        return 2;
    }

    std::cout << "FuftiAntiCheat- Check Memory - ok" << std::endl;

    STARTUPINFOW si;
    PROCESS_INFORMATION pi;
    ZeroMemory(&si, sizeof(si));
    si.cb = sizeof(si);
    ZeroMemory(&pi, sizeof(pi));

    std::wstring cmdLine;
    if (targetGamePath == currentExePath) {
        cmdLine = L"\"" + targetGamePath + L"\" --demo";
    } else {
        cmdLine = L"\"" + targetGamePath + L"\"";
    }

    std::vector<wchar_t> cmdBuf(cmdLine.begin(), cmdLine.end());
    cmdBuf.push_back(0);

    BOOL created = CreateProcessW(
        NULL,
        cmdBuf.data(),
        NULL,
        NULL,
        FALSE,
        CREATE_SUSPENDED,
        NULL,
        NULL,
        &si,
        &pi
    );

    if (!created) {
        return 3;
    }

    if (!InjectAntiCheatDll(pi.hProcess, dllPath)) {
        TerminateProcess(pi.hProcess, 1);
        CloseHandle(pi.hThread);
        CloseHandle(pi.hProcess);
        return 4;
    }

    ResumeThread(pi.hThread);

    RunWatchdogLoop(pi.hProcess);

    CloseHandle(pi.hThread);
    CloseHandle(pi.hProcess);
    return 0;
}

