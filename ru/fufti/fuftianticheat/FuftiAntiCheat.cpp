static std::string XorDecryptStr(const FuftiEncryptedItem& item) {
    std::string s;
    s.resize(item.length);
    for (size_t i = 0; i < item.length; ++i) {
        s[i] = (char)(item.bytes[i] ^ FUFTI_XOR_KEY);
    }
    return s;
}

static std::wstring XorDecryptWStr(const FuftiEncryptedItem& item) {
    std::string s = XorDecryptStr(item);
    return std::wstring(s.begin(), s.end());
}

static std::wstring ToLowerString(const std::wstring& src) {
    std::wstring out = src;
    for (size_t i = 0; i < out.size(); ++i) {
        if (out[i] >= L'A' && out[i] <= L'Z') {
            out[i] = out[i] + (L'a' - L'A');
        }
    }
    return out;
}




static void TerminateSuspectProcess(DWORD suspectPid) {
    if (suspectPid == 0 || suspectPid == GetCurrentProcessId()) {
        return;
    }
    HANDLE hSuspect = OpenProcess(PROCESS_TERMINATE, FALSE, suspectPid);
    if (hSuspect != NULL) {
        TerminateProcess(hSuspect, 0xC0000022);
        CloseHandle(hSuspect);
    }
}

